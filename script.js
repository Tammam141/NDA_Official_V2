// --- default state ---
let currentLang = localStorage.getItem("nda_lang") || "id";
let currentTheme = localStorage.getItem("nda_theme") || "light";

// --- dynamic wa link generator ---
function updateWhatsAppLinks() {
  const waBtnElements = document.querySelectorAll(".btn-catalog-wa, .btn-detail-wa");
  const waBase = "https://wa.me/628568636423";
  
  waBtnElements.forEach(btn => {
    const prodName = btn.getAttribute("data-product-name");
    let text = "";
    
    if (currentLang === "id") {
      text = `Halo admin NDA V2! Saya tertarik untuk memesan produk *${prodName}* yang saya lihat di website. Apakah stoknya masih tersedia?`;
    } else {
      text = `Hello NDA V2 admin! I'm interested in ordering the *${prodName}* that I saw on the website. Is it currently in stock?`;
    }
    
    btn.href = `${waBase}?text=${encodeURIComponent(text)}`;
  });
}

// --- language switcher controller ---
function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("nda_lang", lang);
  
  // translate elements
  const elements = document.querySelectorAll("[data-i18n]");
  elements.forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // translate specific inner HTML elements if required
  const htmlElements = document.querySelectorAll("[data-i18n-html]");
  htmlElements.forEach(el => {
    const key = el.getAttribute("data-i18n-html");
    if (translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  // update selected language checkmarks in dropdown UI
  document.querySelectorAll(".lang-item").forEach(item => {
    if (item.getAttribute("data-lang") === lang) {
      item.classList.add("active");
    } else {
      item.classList.remove("active");
    }
  });

  // update current language label
  const langLabel = document.getElementById("currentLangLabel");
  if (langLabel) {
    langLabel.textContent = lang.toUpperCase();
  }

  // Update Dynamic URLs
  updateWhatsAppLinks();
  updateEmailLink();
}

// --- email link builder ---
function updateEmailLink() {
  const emailLink = document.getElementById("emailLink");
  if (!emailLink) return;
  
  const emailTujuan = "ndajayaselalu@gmail.com";
  let subject = "";
  let body = "";
  
  if (currentLang === "id") {
    subject = "Tanya Seputar Produk NDA Fashion Hijab V2";
    body = "Halo Admin NDA,\n\nSaya tertarik dengan produk Anda dan ingin bertanya mengenai detail atau stok produk.\n\nTerima kasih.";
  } else {
    subject = "Inquiry Regarding NDA Fashion Hijab V2 Products";
    body = "Hello NDA Admin,\n\nI am interested in your products and would like to ask about the details or stock availability.\n\nThank you.";
  }

  const isMobile = /iPhone|iPad|iPod|Android/i.test(navigator.userAgent);
  if (isMobile) {
    emailLink.href = `mailto:${emailTujuan}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
  } else {
    emailLink.href = `https://mail.google.com/mail/?view=cm&fs=1&to=${emailTujuan}&su=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
  }
}

// --- dark mode switcher controller ---
function setTheme(theme) {
  currentTheme = theme;
  localStorage.setItem("nda_theme", theme);
  document.documentElement.setAttribute("data-bs-theme", theme);
  
  const toggleBtn = document.getElementById("themeToggle");
  if (toggleBtn) {
    const icon = toggleBtn.querySelector("i");
    const label = toggleBtn.querySelector("#themeLabel");
    if (theme === "dark") {
      icon.className = "fas fa-sun";
      if (label) label.textContent = "LIGHT";
      toggleBtn.title = "Mode Terang";
    } else {
      icon.className = "fas fa-moon";
      if (label) label.textContent = "DARK";
      toggleBtn.title = "Mode Gelap";
    }
  }
}

// --- filename active navbar highlighter ---
function initNavbarActiveState() {
  const path = window.location.pathname;
  const navLinks = document.querySelectorAll(".nav-link");
  const bottomNavItems = document.querySelectorAll(".bottom-nav-item");

  function setActive(targetAttr) {
    navLinks.forEach(link => {
      link.classList.remove("active");
      if (link.getAttribute("href") === targetAttr) {
        link.classList.add("active");
      }
    });

    bottomNavItems.forEach(item => {
      item.classList.remove("active");
      if (item.getAttribute("href") === targetAttr) {
        item.classList.add("active");
      }
    });
  }

  if (path.includes("about.html")) {
    setActive("about.html");
  } else if (path.includes("katalog.html") || path.includes("detail-")) {
    setActive("katalog.html");
  } else if (path.includes("contact.html")) {
    setActive("contact.html");
  } else if (path.includes("home.html")) {
    setActive("home.html");
  } else {
    // defaults (root index.html is the linktree, doesn't have standard navbar)
    setActive("home.html");
  }
}

// --- catalog product dynamic filter ---
function initCatalogFilter() {
  const filterPills = document.querySelectorAll(".filter-pill");
  const productItems = document.querySelectorAll(".product-item");

  filterPills.forEach(pill => {
    pill.addEventListener("click", function () {
      // update active pill button
      filterPills.forEach(p => p.classList.remove("active"));
      this.classList.add("active");

      const filterValue = this.getAttribute("data-filter");

      productItems.forEach(item => {
        item.classList.add("fade-out");
        
        setTimeout(() => {
          const itemCategory = item.getAttribute("data-category");
          if (filterValue === "all" || itemCategory === filterValue) {
            item.classList.remove("hidden");
            // small delay to trigger CSS transition smoothly
            setTimeout(() => item.classList.remove("fade-out"), 30);
          } else {
            item.classList.add("hidden");
          }
        }, 300); // matches the transition duration in CSS
      });
    });
  });
}

// --- auto-scroll and video autoplay helper ---
function initAutoplayElements() {
  // Force video autoplay on all video elements
  const videos = document.querySelectorAll("video");
  videos.forEach(video => {
    video.muted = true;
    video.playsInline = true;
    video.autoplay = true;
    // Attempt play
    video.play().catch(err => {
      console.log("Autoplay failed/blocked by browser:", err);
    });
  });

  // Force specified carousels to auto-scroll automatically without pausing on hover
  const targetCarousels = document.querySelectorAll("#testimonialCarousel, #valCarousel, #productCarousel");
  targetCarousels.forEach(carouselEl => {
    const carouselInstance = bootstrap.Carousel.getOrCreateInstance(carouselEl, {
      interval: 3000,
      ride: "carousel",
      pause: false
    });
    carouselInstance.cycle();
  });
}

// --- on document load ---
document.addEventListener("DOMContentLoaded", () => {
  // initialize default language & theme
  setLanguage(currentLang);
  setTheme(currentTheme);
  
  // init components
  initNavbarActiveState();
  initCatalogFilter();
  initAutoplayElements();

  // Theme Toggler Click Listener
  const themeBtn = document.getElementById("themeToggle");
  if (themeBtn) {
    themeBtn.addEventListener("click", () => {
      const nextTheme = currentTheme === "dark" ? "light" : "dark";
      setTheme(nextTheme);
    });
  }

  // Language Dropdown Click Listeners
  document.querySelectorAll(".lang-item").forEach(item => {
    item.addEventListener("click", (e) => {
      e.preventDefault();
      const lang = item.getAttribute("data-lang");
      setLanguage(lang);
    });
  });

  // Smooth Scroll on anchor clicks (useful for home.html inner sections like hero button scroll)
  const smoothScrollLinks = document.querySelectorAll('a[href^="#"]');
  smoothScrollLinks.forEach(anchor => {
    anchor.addEventListener("click", function (e) {
      const targetId = this.getAttribute("href");
      if (targetId === "#") return;
      
      const targetElement = document.querySelector(targetId);
      if (targetElement) {
        e.preventDefault();
        const offset = 80; // offset height of the sticky navbar
        const elementPosition = targetElement.getBoundingClientRect().top;
        const offsetPosition = elementPosition + window.scrollY - offset;
        
        window.scrollTo({
          top: offsetPosition,
          behavior: "smooth"
        });
      }
    });
  });
});

